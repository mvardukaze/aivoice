def test_numbers():
    assert [cardinal(n) for n in (21, 30, 47, 99, 101, 250, 1001, 2024)] == [
        "ოცდაერთი", "ოცდაათი", "ორმოცდაშვიდი", "ოთხმოცდაცხრამეტი", "ას ერთი", "ორას ორმოცდაათი", "ათას ერთი", "ორი ათას ოცდაოთხი"]
    assert [ordinal(n) for n in (1, 2, 8, 21, 100, 101)] == ["პირველი", "მეორე", "მერვე", "ოცდამეერთე", "მეასე", "ას პირველი"]


def test_text():
    for src, want in CASES.items():
        assert ka_text(src) == want, (src, ka_text(src))


if __name__ == "__main__":
    test_numbers()
    test_text()
